/**
 * Deterministic CSS generator for the Phase 0 token foundation.
 *
 * Consumes `../tokens.json` (gated by `./validate.mjs`) and renders
 * `theme-tokens.css`:
 *
 * - motion tokens under `:root`
 * - scheme-independent public/sandbox surface roles, the legacy stop palette,
 *   and the scene chart colors under `:root`
 * - status + viz constants and the skin-3 semantic map under
 *   `[data-scheme='light'][data-skin='3']` / `[data-scheme='dark'][data-skin='3']`
 *   (status and viz are scheme-constant but both blocks carry them so the
 *   custom properties resolve inside each `[data-scheme]` scope; a semantic
 *   value of `null` is omitted from its scheme's block)
 * - a `@media (prefers-reduced-motion: reduce)` override collapsing every
 *   duration to `var(--pf-reduced-motion-fade)` — the var indirection is
 *   deliberate, the fade token itself stays emitted at `:root`
 *
 * Determinism contract (Task 9's CI re-runs this and fails on any diff in
 * `packages/tokens/dist`): emission order follows the key order of
 * tokens.json itself, one property per line at 2-space indent, trailing
 * newline, no minification — two runs produce byte-identical output.
 *
 * Usage:
 * - `build({ outDir })` always returns the CSS string; when `outDir` is
 *   provided it also writes `<outDir>/theme-tokens.css`, creating the
 *   directory if needed.
 * - run directly (`node src/build.mjs`, the root `tokens:build` script) to
 *   write the package's own `dist/theme-tokens.css`, resolved relative to
 *   this module file — never the cwd.
 * - importing this module has no side effects.
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { join } from 'node:path';
import { validateTokens } from './validate.mjs';
import tokens from '../tokens.json' with { type: 'json' };

const FILE_NAME = 'theme-tokens.css';
const SKIN = '3';
const SCHEMES = ['light', 'dark'];

// `--pf-` + dotted-path-to-kebab: `accentSecondary.link` →
// `--pf-accent-secondary-link` (controller ruling 6). Digits pass through.
const cssVarName = (path) =>
  `--pf-${path.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`).replace(/\./g, '-')}`;

const property = (path, value) => `  ${cssVarName(path)}: ${value};`;

const block = (selector, lines) => `${selector} {\n${lines.join('\n')}\n}`;

function motionBlock() {
  const lines = [];
  for (const [band, values] of Object.entries(tokens.motion)) {
    for (const [name, value] of Object.entries(values)) {
      lines.push(property(`${band}.${name}`, value));
    }
  }
  return block(':root', lines);
}

// Scheme-independent surface roles and the legacy stop palette, emitted at
// `:root` so the public stylesheet and the admin shell can stop carrying raw
// hex. `scene.chart` is emitted for CSS gradients (Tailwind mesh utilities);
// the rest of `scene` is consumed by the WebGL layer through @portfolio/tokens.
const ROOT_GROUPS = [
  ['public', 'publicSurface'],
  ['sandbox', 'sandboxSurface'],
  ['legacy-palette', 'legacyPalette'],
];

function rootTokensBlock() {
  const lines = [];
  for (const [prefix, group] of ROOT_GROUPS) {
    for (const [name, leaf] of Object.entries(tokens[group])) {
      lines.push(property(`${prefix}.${name}`, leaf.$value));
    }
  }
  for (const [name, leaf] of Object.entries(tokens.scene.chart)) {
    lines.push(property(`scene.chart.${name}`, leaf.$value));
  }
  return block(':root', lines);
}

function schemeBlock(scheme) {
  const lines = [];
  for (const [name, leaf] of Object.entries(tokens.status)) {
    lines.push(property(`status.${name}`, leaf.$value));
  }
  for (const [name, leaf] of Object.entries(tokens.viz)) {
    lines.push(property(`viz.${name}`, leaf.$value));
  }
  const semantic = tokens.skins[SKIN].semantic;
  for (const [group, tokensInGroup] of Object.entries(semantic)) {
    for (const [name, token] of Object.entries(tokensInGroup)) {
      const value = token[scheme];
      if (value === null) continue; // null value → omitted from this scheme
      lines.push(property(`${group}.${name}`, value));
    }
  }
  return block(`[data-scheme='${scheme}'][data-skin='${SKIN}']`, lines);
}

function reducedMotionBlock() {
  const lines = Object.keys(tokens.motion.dur)
    .map((name) => `    ${cssVarName(`dur.${name}`)}: var(${cssVarName('reducedMotion.fade')});`)
    .join('\n');
  return `@media (prefers-reduced-motion: reduce) {\n  :root {\n${lines}\n  }\n}`;
}

function render() {
  const banner = '/* Generated by packages/tokens/src/build.mjs from tokens.json — do not edit. */';
  return (
    [
      banner,
      motionBlock(),
      rootTokensBlock(),
      schemeBlock('light'),
      schemeBlock('dark'),
      reducedMotionBlock(),
    ].join('\n\n') + '\n'
  );
}

export function build({ outDir } = {}) {
  validateTokens(tokens); // gate: throw before anything is emitted
  const css = render();
  if (outDir !== undefined) {
    mkdirSync(outDir, { recursive: true });
    writeFileSync(join(outDir, FILE_NAME), css, 'utf8');
  }
  return css;
}

const isDirectRun =
  Boolean(process.argv[1]) && import.meta.url === pathToFileURL(process.argv[1]).href;

if (isDirectRun) {
  build({ outDir: fileURLToPath(new URL('../dist/', import.meta.url)) });
}
