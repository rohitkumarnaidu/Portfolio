#!/usr/bin/env node
/**
 * Regenerates docs/MASTER-INDEX.md from the files that exist.
 *
 * The index used to be hand-written for a three-tier platform and drifted out
 * of date (it claimed the backend and admin dashboard were deleted). This
 * walks the tree, so a file that exists is indexed and a file that does not is
 * not linked.
 */
const fs = require('fs');
const path = require('path');

const DOCS = path.join(__dirname, '..', 'docs');
const ROOT = path.join(__dirname, '..');

const TITLES = {
  '04-design': 'Design system',
  '05-architecture': 'Architecture',
  '06-backend': 'Backend',
  '07-frontend': 'Frontend',
  '09-database': 'Database',
  '10-api': 'API',
  '11-security': 'Security',
  '12-devops': 'DevOps',
  '13-testing': 'Testing',
  '14-observability': 'Observability',
  '15-performance': 'Performance',
  '16-accessibility': 'Accessibility',
  '17-seo': 'SEO',
  '19-admin': 'Admin',
  '20-cms': 'CMS',
  '21-operations': 'Operations',
  '22-release': 'Release',
  '23-governance': 'Governance',
  '24-development': 'Development',
  '26-reference': 'Reference',
  '27-decisions': 'Decision records',
  '28-templates': 'Templates',
  '29-checklists': 'Checklists',
  '30-runbooks': 'Runbooks',
  '31-playbooks': 'Playbooks',
  '32-disaster-recovery': 'Disaster recovery',
  '33-onboarding': 'Onboarding',
  '34-contributing': 'Contributing',
  '35-quality': 'Quality',
  archive: 'Archive (unmaintained history)',
  superpowers: 'Superpowers (spec + plans)',
};

const ROOT_DOCS = [
  'AGENTS.md',
  'DESIGN.md',
  'PROGRESS.md',
  'roadmap.md',
  'README.md',
  'CHANGELOG.md',
];

function titleFor(dir) {
  if (TITLES[dir]) return TITLES[dir];
  const name = dir.replace(/^\d+-/, '').replaceAll('-', ' ');
  return name.charAt(0).toUpperCase() + name.slice(1);
}

function markdownFiles(dir, prefix = '') {
  const entries = fs
    .readdirSync(dir, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name));
  const files = [];
  for (const entry of entries) {
    const relative = path.posix.join(prefix, entry.name);
    if (entry.isDirectory()) {
      files.push(...markdownFiles(path.join(dir, entry.name), relative));
    } else if (entry.name.endsWith('.md')) {
      files.push(relative);
    }
  }
  return files;
}

const dirs = fs
  .readdirSync(DOCS, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

const lines = [
  '# Documentation Index',
  '',
  '> Auto-generated by `node scripts/generate-docs-index.js`. Do not edit by hand.',
  '',
  'Every Markdown file that exists under `docs/` plus the root working documents.',
  'Some numbered categories predate the 2.0 architecture and contain stale material;',
  '`docs/archive/` is explicitly unmaintained. Live documents are listed in the',
  'root `AGENTS.md` docs map.',
  '',
  '## Root',
  '',
];

for (const file of ROOT_DOCS) {
  if (fs.existsSync(path.join(ROOT, file))) {
    lines.push(`- [${file.replace(/\.md$/, '')}](${file})`);
  }
}
lines.push('');

for (const dir of dirs) {
  const files = markdownFiles(path.join(DOCS, dir));
  if (files.length === 0) continue;
  lines.push(`## ${titleFor(dir)} (\`${dir}\`)`, '');
  for (const file of files) {
    lines.push(`- [${file.replace(/\.md$/, '')}](${dir}/${file})`);
  }
  lines.push('');
}

const out = path.join(DOCS, 'MASTER-INDEX.md');
fs.writeFileSync(out, lines.join('\n'));
console.log(`wrote ${out} (${dirs.length} categories)`);
